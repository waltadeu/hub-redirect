window.HR = window.HR || {};
window.HR.getLang = function() {
  return localStorage.getItem('hr_lang') || 'pt-BR';
};
window.HR.setLang = function(lang) {
  localStorage.setItem('hr_lang', lang);
  window.HR.applyI18n();
  document.documentElement.setAttribute('lang', lang === 'pt-BR' ? 'pt-BR' : 'en');
  // Update active button
  document.querySelectorAll('.lang-switch button').forEach(btn => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });
};
window.HR.applyI18n = function() {
  const lang = window.HR.getLang();
  const dict = window.HR_I18N[lang] || window.HR_I18N['pt-BR'];
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key] != null) el.textContent = dict[key];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key] != null) el.setAttribute('placeholder', dict[key]);
  });
};
